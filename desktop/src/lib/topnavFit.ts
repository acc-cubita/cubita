/**
 * نردبانِ کوچک‌شدنِ نوارِ بالا — منطقِ خالصش، جدا از DOM.
 *
 * **چرا جداست:** `TopNav` اندازه‌ها را از DOM می‌گیرد و محیطِ تستِ این پروژه
 * `node` است و DOM ندارد. تصمیم این‌جا سنجیده می‌شود، اندازه‌گیری آن‌جا.
 *
 * **قاعده‌ی اصلی، در خودِ نوعِ خروجی:** `SearchShape` فقط دو مقدار دارد و هیچ‌کدام
 * «پنهان» نیست. پیش از این جست‌وجو دو جا کاملاً ناپدید می‌شد (کلاسِ `topnav--tight`
 * و `@media (max-width: 760px)`)، و زیرِ ۷۶۰px — بیرون از داشبورد — هیچ راهی به
 * جست‌وجو نمی‌ماند: کشوی همبرگری کادر ندارد و `Ctrl+K` روی موبایل صفحه‌کلیدی ندارد
 * که زده شود. حالا نوشتنِ آن حالت ممکن نیست.
 *
 * **همبرگر جایگزینِ منوست، نه اضافه بر آن.** نوار دو چیدمانِ ممکن دارد و هزینه‌شان
 * فرق می‌کند: یا منو روی نوار است و همبرگری نیست، یا منو در کشوست و همبرگر هست.
 * سنجشِ قبلی همبرگر را اصلاً نمی‌شمرد و روی ۳۹۰px همان ۴۴px نشمرده، نوار را از لبه
 * بیرون می‌زد؛ شمردنِ همیشگی‌اش هم اشتباهِ قرینه بود — نوار را در عرض‌های میانی
 * بی‌دلیل به کشو می‌فرستاد. این‌جا هر چیدمان با هزینه‌ی خودش سنجیده می‌شود.
 */

/** نمایِ جست‌وجو در نوار. «پنهان» عمداً وجود ندارد. */
export type SearchShape = 'pill' | 'icon'

/** جای منوی ماژول‌ها: روی نوار، یا داخلِ کشوی همبرگری. */
export type MenuPlace = 'bar' | 'drawer'

export interface BarMetrics {
  /**
   * عرضِ نوار **بدونِ منو، بدونِ همبرگر و بدونِ جست‌وجو**: برند، بقیه‌ی کنش‌ها،
   * padding و فاصله‌ها.
   */
  bare: number
  /** عرضِ طبیعیِ منوی ماژول‌ها. */
  menu: number
  /** عرضِ همبرگر — فقط در چیدمانی که منو به کشو رفته خرج می‌شود. */
  hamburger: number
  /** عرضِ قرصِ نوشته‌دارِ جست‌وجو. */
  pill: number
  /** عرضِ ذره‌بین. */
  icon: number
  /** عرضِ در دسترس — `clientWidth`ِ ظرفِ نوار. */
  avail: number
}

export interface BarFit {
  search: SearchShape
  menu: MenuPlace
}

/**
 * چهار چیدمانِ ممکن را به ترتیبِ مطلوبیت می‌آزماید و اولینی را که جا می‌شود
 * برمی‌گرداند.
 *
 * ترتیب عمدی است: **دیده‌شدنِ ماژول‌ها روی نوار از نوشته‌ی کنارِ ذره‌بین مهم‌تر
 * است**، پس پیش از فرستادنِ منو به کشو، اول قرص به ذره‌بین جمع می‌شود. و اگر منو
 * ناچار به کشو رفت، جایی که آزاد می‌شود دوباره به قرص می‌رسد.
 *
 * چون هر چهار حالت در *یک* سنجش آزموده می‌شوند، هیچ‌کدام به حالتِ فعلیِ نوار
 * وابسته نیست و نوار بین دو حالت نمی‌لرزد.
 */
export function fitBar(m: BarMetrics): BarFit {
  const onBar = m.bare + m.menu
  if (onBar + m.pill <= m.avail) return { search: 'pill', menu: 'bar' }
  if (onBar + m.icon <= m.avail) return { search: 'icon', menu: 'bar' }

  const inDrawer = m.bare + m.hamburger
  if (inDrawer + m.pill <= m.avail) return { search: 'pill', menu: 'drawer' }
  return { search: 'icon', menu: 'drawer' }
}
