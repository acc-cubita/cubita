/**
 * نردبانِ کوچک‌شدنِ نوارِ بالا — منطقِ خالصش، جدا از DOM.
 *
 * **چرا جداست:** `TopNav` اندازه‌ها را از DOM می‌گیرد و محیطِ تستِ این پروژه
 * `node` است و DOM ندارد. تصمیم این‌جا سنجیده می‌شود، اندازه‌گیری آن‌جا.
 *
 * **همبرگر مالِ تبلت و گوشی است، نه دسکتاپ** (خواستِ آرش، ۱۴۰۵/۰۷/۰۶). روی تبلت و گوشی خودِ CSS
 * منو را برمی‌دارد (`display:none` تا ۱۰۲۴px، و روی دستگاهِ لمسی تا ۱۲۸۰px که تبلتِ ۱۱ اینچ در حالتِ
 * افقی هم زیرش است) و `menu` این‌جا `Infinity` می‌رسد. روی دسکتاپ منو **همیشه روی نوار است**: با قلمِ
 * استاندارد وقتی جا هست، و وقتی نیست همه‌ی ماژول‌ها با هم و به یک نسبت کوچک می‌شوند تا همه دیده شوند.
 * کشو روی دسکتاپ فقط تورِ ایمنی است: وقتی جا دادن قلم را زیرِ حدِ خوانایی می‌برد.
 *
 * **قاعده‌ی جست‌وجو، در خودِ نوعِ خروجی:** `SearchShape` فقط دو مقدار دارد و هیچ‌کدام «پنهان» نیست.
 * پیش از این جست‌وجو زیرِ ۷۶۰px کاملاً ناپدید می‌شد و — بیرون از داشبورد — هیچ راهی به آن نمی‌ماند.
 *
 * **همبرگر جایگزینِ منوست، نه اضافه بر آن:** یا منو روی نوار است و همبرگری نیست، یا منو در کشوست و
 * همبرگر هست؛ هر چیدمان با هزینه‌ی خودش سنجیده می‌شود.
 */

/** نمایِ جست‌وجو در نوار. «پنهان» عمداً وجود ندارد. */
export type SearchShape = 'pill' | 'icon'

/** جای منوی ماژول‌ها: روی نوار، یا داخلِ کشوی همبرگری. */
export type MenuPlace = 'bar' | 'drawer'

/**
 * کوچک‌ترین ضریبِ منو. قلمِ استاندارد ۱۳px است، پس ۰٫۷۳ یعنی ~۹٫۵px — زیرِ این نوشته‌ی فارسیِ منو
 * دیگر خوانا نیست و کشو بهتر از منویی است که نمی‌شود خواند. با ۱۳ ماژول این حد روی دسکتاپ فقط زیرِ
 * ~۱۰۵۰px می‌رسد.
 */
export const MIN_MENU_SCALE = 0.73

/** چند پیکسل کم‌تر از جای آزاد: پهنای نوشته دقیقاً خطی نیست (گرد‌شدنِ قلم و نشانِ خوانده‌نشده). */
const SLACK = 2

export interface BarMetrics {
  /**
   * عرضِ نوار **بدونِ منو، بدونِ همبرگر و بدونِ جست‌وجو**، با نوارِ کامل (نامِ کنارِ نشان و
   * نوشته‌ی «دانلودِ دسکتاپ» دیده می‌شوند): بقیه‌ی کنش‌ها، padding و فاصله‌ها.
   */
  bare: number
  /** همان، در حالتِ فشرده: نامِ کنارِ نشان و نوشته‌ی دکمه‌ی دانلود پنهان‌اند. */
  compactBare: number
  /** عرضِ طبیعیِ منوی ماژول‌ها با قلمِ استاندارد (ضریبِ ۱) — همان بخشی که کوچک می‌شود. `Infinity` یعنی CSS منو را برداشته. */
  menu: number
  /** بخشِ ثابتِ هزینه‌ی منو روی نوار (فاصله‌ی کنارش) که با ضریب کوچک نمی‌شود. */
  menuFixed: number
  /** عرضِ همبرگر — فقط در چیدمانی که منو به کشو رفته خرج می‌شود. */
  hamburger: number
  /** عرضِ قرصِ نوشته‌دارِ جست‌وجو. */
  pill: number
  /** عرضِ ذره‌بین. */
  icon: number
  /** عرضِ در دسترس — `clientWidth`ِ ظرفِ نوار. */
  avail: number
}

export interface BarFit {
  search: SearchShape
  menu: MenuPlace
  /** نامِ کنارِ نشان و نوشته‌ی «دانلودِ دسکتاپ» پنهان شوند. */
  compact: boolean
  /** ضریبِ قلم و فاصله‌ی ماژول‌ها؛ ۱ یعنی اندازه‌ی استاندارد. */
  scale: number
}

/**
 * چیدمان‌ها را به ترتیبِ مطلوبیت می‌آزماید و اولینی را که جا می‌شود برمی‌گرداند:
 *
 * 1. همه‌چیز در اندازه‌ی استاندارد، جست‌وجو با قرص؛
 * 2. قرص به ذره‌بین جمع می‌شود؛
 * 3. نوار فشرده می‌شود (نامِ کنارِ نشان و نوشته‌ی دانلود) — هنوز قلمِ استاندارد؛
 * 4. ماژول‌ها به یک نسبت کوچک می‌شوند، تا `MIN_MENU_SCALE`؛
 * 5. فقط اگر این هم کافی نبود (یا CSS منو را برداشته — تبلت و گوشی)، کشوی همبرگری.
 *
 * ترتیب عمدی است: **خوانا ماندنِ ماژول‌ها از نوشته‌ی کنارِ ذره‌بین و نامِ کنارِ نشان مهم‌تر است** —
 * نشان خودش برند را می‌گوید و دکمه‌ی دانلود با آیکون و `title` همچنان پیداست.
 *
 * هر پنج حالت در *یک* سنجش آزموده می‌شوند و هیچ‌کدام به حالتِ فعلیِ نوار وابسته نیست، پس نوار بین
 * دو حالت نمی‌لرزد.
 */
export function fitBar(m: BarMetrics): BarFit {
  const menuAt = (scale: number) => m.menuFixed + m.menu * scale
  if (m.bare + menuAt(1) + m.pill <= m.avail) return { search: 'pill', menu: 'bar', compact: false, scale: 1 }
  if (m.bare + menuAt(1) + m.icon <= m.avail) return { search: 'icon', menu: 'bar', compact: false, scale: 1 }
  if (m.compactBare + menuAt(1) + m.icon <= m.avail) return { search: 'icon', menu: 'bar', compact: true, scale: 1 }

  //: `menu` بی‌نهایت (منوی برداشته‌شده) ضریبِ صفر می‌دهد و مستقیم به کشو می‌رسد.
  const room = m.avail - m.compactBare - m.menuFixed - m.icon - SLACK
  const scale = Math.floor((room / m.menu) * 1000) / 1000
  if (scale >= MIN_MENU_SCALE) return { search: 'icon', menu: 'bar', compact: true, scale }

  const inDrawer = m.bare + m.hamburger
  if (inDrawer + m.pill <= m.avail) return { search: 'pill', menu: 'drawer', compact: false, scale: 1 }
  return { search: 'icon', menu: 'drawer', compact: false, scale: 1 }
}

/** دو نتیجه یکی‌اند؟ — تا `TopNav` با هر سنجشِ بی‌تغییر دوباره رندر نشود. */
export function sameFit(a: BarFit, b: BarFit): boolean {
  return a.search === b.search && a.menu === b.menu && a.compact === b.compact && a.scale === b.scale
}
