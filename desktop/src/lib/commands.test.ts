/**
 * تطبیقِ جست‌وجوی ماژول.
 *
 * قیدی که این فایل نگه می‌دارد: **کاربر نباید مجبور باشد عینِ برچسب را تایپ
 * کند.** پیش از این تطبیق `includes` خام بود، پس «طرف حساب» با فاصله‌ی معمولی
 * منویی با نیم‌فاصله را پیدا نمی‌کرد و کاربر نتیجه می‌گرفت که چنین چیزی نیست.
 * اگر روزی کسی نرمال‌سازی را بردارد، همان سکوت برمی‌گردد.
 */
import { describe, it, expect } from 'vitest'

import { normalizeFa, textMatches } from './commands'

describe('یکسان‌سازیِ متن', () => {
  it('نیم‌فاصله فاصله می‌شود', () => {
    expect(normalizeFa('طرف‌حساب')).toBe('طرف حساب')
  })

  it('ي و ك عربی به فارسی برمی‌گردند', () => {
    //: روی کیبوردِ عربیِ ویندوز این دو حرف خیلی راحت تایپ می‌شوند.
    expect(normalizeFa('كالا')).toBe('کالا')
    expect(normalizeFa('مشتري')).toBe('مشتری')
  })

  it('ارقامِ فارسی و عربی لاتین می‌شوند', () => {
    expect(normalizeFa('۱۴۰۵')).toBe('1405')
    expect(normalizeFa('١٤')).toBe('14')
  })

  it('فاصله‌های اضافی جمع می‌شوند', () => {
    expect(normalizeFa('  فاکتور   فروش  ')).toBe('فاکتور فروش')
  })
})

describe('تطبیق', () => {
  it('**هسته‌ی این تغییر** — فاصله‌ی معمولی، نیم‌فاصله را پیدا می‌کند', () => {
    expect(textMatches('طرف‌حساب‌ها', 'طرف حساب')).toBe(true)
  })

  it('و برعکس', () => {
    expect(textMatches('طرف حساب‌ها', 'طرف‌حساب')).toBe(true)
  })

  it('ترتیبِ واژه‌ها مهم نیست', () => {
    //: کاربر «فروش فاکتور» تایپ می‌کند چون در ذهنش اول ماژول است.
    expect(textMatches('فاکتور فروش', 'فروش فاکتور')).toBe(true)
  })

  it('واژه‌ی بی‌ربط نتیجه را رد می‌کند', () => {
    expect(textMatches('فاکتور فروش', 'فاکتور انبار')).toBe(false)
  })

  it('کوئریِ خالی همه را می‌گیرد، نه هیچ‌کدام', () => {
    //: کامندپالت بی‌کوئری کلِ فهرست را نشان می‌دهد؛ اگر این false شود، خالی باز می‌شود.
    expect(textMatches('هرچیزی', '   ')).toBe(true)
  })

  it('لاتین به بزرگی و کوچکی حساس نیست', () => {
    expect(textMatches('Cubita POS', 'cubita pos')).toBe(true)
  })
})
