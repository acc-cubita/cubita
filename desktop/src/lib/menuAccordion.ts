/**
 * آکاردئونِ دسته‌های منوی ماژول (۱۴۰۵/۰۷/۰۶، خواستِ آرش): **پیش‌فرض همه‌ی دسته‌ها بسته‌اند** و باز کردنِ یکی،
 * دسته‌ی بازِ دیگرِ همان منو را می‌بندد.
 *
 * - هر ماژول (`scope` = نامِ گروه) دسته‌ی بازِ خودش را دارد؛ باز کردن در «حسابداری» منوی «فروش» را عوض نمی‌کند.
 * - فقط در حافظه‌ی همین اجراست، نه `localStorage`: رفتن به صفحه‌ی دیگر یا ماژولِ دیگر و برگشتن دسته را باز نگه
 *   می‌دارد، ولی برنامه‌ی تازه‌باز همیشه با همه‌ی دسته‌های بسته شروع می‌شود — «پیش‌فرض بسته» همین است. پیش از این
 *   بازوبسته‌ی هر دسته جداگانه در `localStorage` می‌ماند و چند دسته با هم باز می‌ماندند.
 * - دسته‌ی بسته‌ای که صفحه‌ی فعال در آن است نشان می‌گیرد (`has-current`)، پس «کجای منو هستم؟» بی باز بودن هم جواب دارد.
 *
 * بی React تا مستقیم تست شود؛ `ModulePanels` بعد از هر تغییر خودش را دوباره می‌کشد.
 */
const open = new Map<string, string>()

/** دسته‌ی بازِ این منو، یا `null` اگر همه بسته‌اند. */
export const openCategory = (scope: string): string | null => open.get(scope) ?? null

/** دسته‌ی باز را می‌بندد؛ دسته‌ی بسته را باز می‌کند و هر دسته‌ی بازِ دیگرِ همین منو را می‌بندد. */
export function toggleCategory(scope: string, title: string): string | null {
  if (open.get(scope) === title) open.delete(scope)
  else open.set(scope, title)
  return openCategory(scope)
}

/** همه بسته — برای تست، معادلِ اجرای تازه‌ی برنامه. */
export const resetOpenCategories = () => open.clear()
