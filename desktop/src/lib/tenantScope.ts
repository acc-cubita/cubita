/**
 * کلیدهای `sessionStorage` به‌ازای کسب‌وکار.
 *
 * `sessionStorage` مالِ تبِ مرورگر است، نه کسب‌وکار. تعویضِ کسب‌وکار (`TenantSwitcher`)
 * فقط `window.location.reload()` می‌زند و این حافظه سرِ جایش می‌ماند. کلیدی که
 * کسب‌وکار در آن نیست، وضعیتِ کسب‌وکارِ قبلی را روی کسب‌وکارِ تازه می‌نشاند:
 * «مرور حساب‌ها» فیلترِ مرکز هزینه‌ی کسب‌وکارِ دیگری را به سرور می‌فرستاد و درخت
 * بی‌صدا خالی می‌آمد، و حافظه‌ی شرحِ سند شرح‌های کسب‌وکارِ دیگر را پیشنهاد می‌داد.
 *
 * **چرا متغیرِ ماژول و نه prop.** حافظه‌ی شرح از سه جای دور از هم خوانده و نوشته
 * می‌شود (پیش‌نویسِ سند، گرید، کادرِ شرح)، و رساندنِ شناسه‌ی کسب‌وکار به هر سه یعنی
 * عوض‌کردنِ امضای چند مؤلفه برای یک رشته.
 *
 * `App` آن را **هنگامِ رندر** از `me.tenant_id` پر می‌کند، نه در افکت. مقدارِ اولیه‌ی
 * `useState`ِ صفحه در همان رندر خوانده می‌شود، و افکتِ `App` بعد از رندرِ فرزندان
 * اجرا می‌شد. مقداردهی هم‌توان است، پس رندرِ دوباره ضرری ندارد.
 */
let tenantId: string | null = null

export function setTenantScope(id: string | null): void {
  tenantId = id
}

/**
 * کلیدِ `base` برای کسب‌وکارِ جاری. `null` یعنی هنوز کسب‌وکاری نیست (پیش از ورود)،
 * و فراخوان نباید چیزی بخواند یا بنویسد. کلیدِ بی‌کسب‌وکار همان خطای قبلی است.
 */
export function tenantKey(base: string): string | null {
  return tenantId ? `${base}:${tenantId}` : null
}
