function GuideAccordionItem({
  entry,
  open,
  onToggle,
}: {
  entry: GuideEntry
  open: boolean
  onToggle: () => void
}) {
  const Icon = entry.icon
  return (
    <div className={`help-accordion-item${open ? ' open' : ''}`}>
      <button type="button" className="help-accordion-trigger" onClick={onToggle} aria-expanded={open}>
        <span className="help-accordion-icon">
          <Icon size={16} />
        </span>
        <span className="help-accordion-heading">
          <span className="help-accordion-title">{entry.title}</span>
          <span className="help-accordion-summary">{entry.summary}</span>
        </span>
        <ChevronDown size={16} className="help-accordion-chevron" />
      </button>
      {open && (
        <div className="help-accordion-body">
          {entry.intro && <p className="help-intro">{entry.intro}</p>}
          <ol className="help-steps">
            {entry.steps.map((step, idx) => (
              <li key={idx}>{step}</li>
            ))}
          </ol>
          {entry.tip && (
            <div className="help-tip">
              <Lightbulb size={14} />
              <span>{entry.tip}</span>
            </div>
          )}
        </div>
      )}
    </div>
  )
}

