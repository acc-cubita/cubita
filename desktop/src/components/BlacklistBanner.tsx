import { AlertTriangle } from 'lucide-react'

/**
 * هشدارِ «این طرف حساب در لیستِ سیاه است» هنگام صدور فاکتور.
 *
 * عمداً **بلاک‌کننده نیست.** لیستِ سیاه یعنی «با احتیاط»، نه «ممنوع»: گاهی آگاهانه و
 * موقتاً برای همان شخص فاکتور می‌زنیم. اگر ثبت را می‌بست، کاربر برای اینکه کارش راه
 * بیفتد تیک را برمی‌داشت و دیگر یادش نمی‌رفت دوباره بزند — یعنی نشانه برای همیشه از
 * بین می‌رفت و دفعه‌ی بعد هیچ هشداری در کار نبود.
 *
 * همان قاعده‌ی سقفِ اعتبار در [بنر اعتبار](./SalesInvoiceForm.tsx): گزارش می‌کنیم،
 * جلو نمی‌گیریم. (`is_blacklisted` جدا از `is_active` است: غیرفعال یعنی دیگر کار
 * نمی‌کنیم، لیستِ سیاه یعنی کار می‌کنیم ولی حواسمان هست.)
 */
export function BlacklistBanner({ name }: { name?: string }) {
  return (
    <div className="credit-banner credit-banner--warn">
      <AlertTriangle size={15} />
      {/* هر دو باید فرزندِ *مستقیمِ* بنر باشند: `credit-banner-alert` با
          `flex-basis: 100%` خودش را به خطِ بعد می‌برد، و تودرتو که باشد دیگر
          آیتمِ فلکس نیست و این اثر از بین می‌رود. */}
      <span><strong>{name || 'این طرف حساب'}</strong> در لیستِ سیاه است.</span>
      <span className="credit-banner-alert">
        ثبتِ فاکتور بسته نیست، ولی پیش از ادامه بررسی کنید.
      </span>
    </div>
  )
}
