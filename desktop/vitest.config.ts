import { defineConfig } from 'vitest/config'

/**
 * پیکربندیِ تستِ دسکتاپ.
 *
 * **چرا جدا از `vite.config.ts`.** آن فایل پلاگینِ Electron را لود می‌کند که
 * موقعِ اجرا پردازه‌ی electron باز می‌کند — چیزی که یک اجرای تست نباید انجام
 * دهد. این‌جا فقط چیزی هست که تست لازم دارد.
 *
 * **دامنه عمداً باریک است.** فایل‌های `*.test.ts` در `src/` و `electron/`،
 * به‌علاوه‌ی `*.test.mjs` در `scripts/`. `node_modules` و خروجی‌های بیلد کنار
 * گذاشته می‌شوند وگرنه اجرا دقیقه‌ها طول می‌کشد و کسی دیگر اجرایش نمی‌کند — و
 * تستی که اجرا نشود، تست نیست.
 *
 * `scripts/` دیرتر اضافه شد و دلیلش مشخص است: ابزارِ ممیزی که خودش سنجیده نشود،
 * روزی بی‌صدا از کار می‌افتد و کسی خبردار نمی‌شود، چون خروجیِ «۰ خطا» هم وقتی
 * درست کار می‌کند همان است و هم وقتی کور شده.
 *
 * محیطِ **پیش‌فرض** `node` است نه DOM: بیشترِ تست‌ها منطقِ خالص‌اند (پروتکلِ
 * کارتخوان، قاعده‌ی تخفیف، صفحه‌بندی) و `jsdom` روی همه‌شان فقط اجرا را کند
 * می‌کند.
 *
 * **استثنا، پرونده‌به‌پرونده.** فایلی که واقعاً DOM می‌خواهد خودش بالای خودش
 * `// @vitest-environment jsdom` می‌نویسد. عمداً این راه به‌جای
 * `environmentMatchGlobs` یا پروژه‌ی دوم انتخاب شد: هیچ پیکربندیِ سراسری‌ای
 * عوض نمی‌شود و خواننده‌ی فایل همان بالا می‌بیند که چرا این یکی فرق دارد.
 *
 * `*.test.tsx` هم پذیرفته می‌شود — تستِ کامپوننت بدونِ JSX خواندنی نیست.
 * اولین نمونه‌اش `SearchSelect.focus.test.tsx` است: رفتارِ فوکوس فقط با DOM
 * سنجیده می‌شود و باگی که آن پرونده قفلش می‌کند یک‌بار به تولید رسید.
 *
 * **`jsdom` ۲۶ دیگر قفل نیست.** تا CI روی Node 20 بود، jsdomِ ۳۰ آن‌جا با
 * `webidl.util.markAsUncloneable is not a function` می‌شکست (موتورش
 * `^22.22.2 || ^24.15.0 || >=26` است). CI حالا روی Node 22 است و قفل برداشته شد.
 * اگر روزی CI دوباره پایین آمد، همین شکست برمی‌گردد — دلیلش همین‌جاست.
 */
export default defineConfig({
  test: {
    environment: 'node',
    include: [
      'src/**/*.test.ts',
      'src/**/*.test.tsx',
      'electron/**/*.test.ts',
      'scripts/**/*.test.mjs',
    ],
    exclude: ['node_modules/**', 'dist/**', 'dist-electron/**', 'release/**'],
    //: خروجیِ کوتاه؛ جزئیات فقط وقتی چیزی می‌شکند.
    reporters: 'dot',
  },
})
