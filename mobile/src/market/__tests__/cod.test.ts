/**
 * نقدِ هنگامِ تحویل.
 *
 * اینجا پول جابه‌جا می‌شود: عددی که مأمورِ حمل وارد می‌کند به درصد تبدیل و به
 * بک‌اند فرستاده می‌شود، و بک‌اند دوباره مبلغ می‌سازد. اگر رفت‌وبرگشت دقیق نباشد،
 * سندِ خزانه‌ی دو کسب‌وکار با آنچه روی صفحه دیده شد فرق می‌کند — بدونِ هیچ خطایی.
 */
import { cashAmountFor, cashPercentFor } from '../cod'

describe('درصد از روی مبلغ', () => {
  it('هیچ نقدی یعنی صفر — سفارشِ کاملاً اعتباری', () => {
    expect(cashPercentFor(0, 5_000_000)).toBe('0')
  })

  it('کلِ مبلغ یعنی صد', () => {
    expect(cashPercentFor(5_000_000, 5_000_000)).toBe('100')
  })

  it('نصف', () => {
    expect(cashPercentFor(2_500_000, 5_000_000)).toBe('50')
  })

  it('بیشتر از کلِ سفارش به کل بریده می‌شود', () => {
    // مأمورِ حمل نمی‌تواند بیشتر از مبلغِ سفارش نقد ثبت کند؛ بک‌اند هم همین کار
    // را می‌کند، ولی کاربر باید *پیش* از ثبت ببیند چه ثبت می‌شود.
    expect(cashPercentFor(9_999_999, 5_000_000)).toBe('100')
  })

  it('منفی صفر می‌شود', () => {
    expect(cashPercentFor(-1, 5_000_000)).toBe('0')
  })

  it('سفارشِ صفر NaN نمی‌سازد', () => {
    // بدونِ این، درصد NaN می‌شد و بک‌اند ۴۲۲ می‌داد — با پیامی که کاربر نمی‌فهمد.
    expect(cashPercentFor(1000, 0)).toBe('0')
  })

  it('ورودیِ نامعتبر صفر می‌شود', () => {
    expect(cashPercentFor(NaN, 5_000_000)).toBe('0')
  })
})

describe('رفت‌وبرگشت — مبلغی که کاربر دید همان است که ثبت می‌شود', () => {
  const CASES: [number, number][] = [
    [1, 3],
    [1_000_000, 3_000_000],
    [333_333, 1_000_000],
    [7, 1_000_000_000],
    [123_456_789, 987_654_321],
    [1, 100_000_000_000],
    [99_999_999_999, 100_000_000_000],
  ]

  it.each(CASES)('مبلغِ %s از کلِ %s', (amount, total) => {
    const pct = cashPercentFor(amount, total)
    expect(cashAmountFor(Number(pct), total)).toBe(amount)
  })
})

describe('بازتابِ محاسبه‌ی بک‌اند', () => {
  it('گِردکردنِ نیم‌به‌بالا', () => {
    // بک‌اند ROUND_HALF_UP دارد؛ اگر اینجا به‌پایین گِرد کنیم، عددِ روی صفحه یک
    // ریال با دفتر فرق می‌کند و کسی سالِ بعد دنبالش می‌گردد.
    expect(cashAmountFor(50, 5)).toBe(3)
  })

  it('درصدِ بیش از صد بریده می‌شود', () => {
    expect(cashAmountFor(150, 1_000)).toBe(1_000)
  })

  it('درصدِ منفی صفر می‌شود', () => {
    expect(cashAmountFor(-10, 1_000)).toBe(0)
  })

  it('سفارشِ صفر صفر می‌ماند', () => {
    expect(cashAmountFor(100, 0)).toBe(0)
  })
})
