/**
 * تطبیقِ متنِ فارسی — بی‌وابستگی به مدلِ ناوبری.
 *
 * این دو تابع در `lib/commands.tsx` زندگی می‌کردند، و چون `SearchSelect` از
 * آنجا واردشان می‌کرد، زنجیره‌ی `FormKit → SearchSelect → commands → buildNav`
 * درست شده بود: «بازاستفاده از فرم‌کیت» عملاً یعنی «بازاستفاده از کلِ مدلِ
 * ناوبریِ اپِ مشتری». همین زنجیره جلوی استفاده‌ی اپِ ستاد از فرم‌کیت را می‌گرفت.
 *
 * `commands.tsx` هنوز همین‌ها را دوباره export می‌کند تا مصرف‌کننده‌های فعلی
 * دست‌نخورده بمانند.
 */
/**
 * یکسان‌سازیِ متنِ فارسی پیش از تطبیق.
 *
 * **چرا لازم است:** تطبیقِ قبلی `includes` خام بود، پس «طرف حساب» با فاصله‌ی
 * معمولی، منویی به نامِ «طرف‌حساب» با نیم‌فاصله را پیدا **نمی‌کرد** — و کاربر
 * نتیجه می‌گرفت که «نیست»، نه اینکه «جور دیگری نوشته شده». همین برای «ي» و «ك»ِ
 * عربی که روی کیبوردهای ویندوز خیلی راحت تایپ می‌شوند، و ارقامِ فارسی.
 */
export function normalizeFa(text: string): string {
  return text
    .replace(/‌|‏|‎/g, ' ') //: نیم‌فاصله و نشانه‌های جهت → فاصله
    .replace(/ـ/g, '') //: کشیدگی (ـ)
    .replace(/[ً-ْ]/g, '') //: اعرابِ عربی
    .replace(/[يى]/g, 'ی') //: ي ى → ی
    .replace(/ك/g, 'ک') //: ك → ک
    .replace(/ة/g, 'ه') //: ة → ه
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 0x06f0)) //: ارقامِ فارسی
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x0660)) //: ارقامِ عربی
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim()
}

/**
 * آیا این متن به آنچه کاربر تایپ کرده می‌خورد؟ هر واژه **جدا** سنجیده می‌شود، پس
 * «فروش فاکتور» هم «فاکتور فروش» را پیدا می‌کند — کاربر ترتیبِ واژه‌ها را حفظ نمی‌کند.
 */
export function textMatches(haystack: string, query: string): boolean {
  const q = normalizeFa(query)
  if (!q) return true
  const hay = normalizeFa(haystack)
  return q.split(' ').every((word) => hay.includes(word))
}

/**
 * رتبه‌ی یک گزینه‌ی تطبیق‌خورده — کوچک‌تر یعنی بالاتر در فهرست.
 *
 * `textMatches` فقط می‌گوید «هست یا نه»، و فهرست به ترتیبِ اصلی می‌ماند. برای حساب‌ها
 * این یعنی تایپِ «۱۱» حسابِ «۲۱۱۰» را هم‌تراز با «۱۱۰۱» نشان می‌داد، و با سقفِ نمایشِ
 * پاپ‌آور، حسابِ درست حتی ممکن بود بیرون بیفتد. قاعده همان که حسابدار انتظار دارد:
 *
 * - ۰: خودِ برچسب با عبارت شروع می‌شود (کدِ حساب: «۱۱» ← «۱۱۰۱ — …»).
 * - ۱: یکی از واژه‌های برچسب با آن شروع می‌شود (نام: «بان» ← «۱۱۰۱ — بانک ملی»).
 * - ۲: فقط جایی در میانه هست.
 *
 * برای عبارتِ چندواژه‌ای واژه‌ی اول ملاک است؛ بقیه را `textMatches` تضمین کرده.
 */
export function matchRank(label: string, query: string): number {
  const q = normalizeFa(query).split(' ')[0] ?? ''
  if (!q) return 0
  const hay = normalizeFa(label)
  if (hay.startsWith(q)) return 0
  //: جداکننده‌ی «کد — نام» و خط‌تیره/اسلش هم مرزِ واژه‌اند.
  return hay.split(/[\s\-—–/،,]+/).some((w) => w.startsWith(q)) ? 1 : 2
}
