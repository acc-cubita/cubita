from pydantic import BaseModel, Field

#: سقفِ تعدادِ کارت. باکسِ داشبورد یک گریدِ چندستونه است؛ بیش از این، خودش می‌شود
#: یک منوی دوم و کاربر همان جایی می‌رسد که می‌خواست از آن فرار کند.
MAX_CARDS = 24

#: سقفِ طولِ شناسه — `page/section`. بلندترینِ امروزی حدودِ ۳۰ نویسه است.
MAX_CARD_ID = 80


class DashboardCardsIn(BaseModel):
    """کارت‌های انتخابیِ کاربر، به ترتیبِ نمایش.

    اعتبارِ *معناییِ* شناسه‌ها این‌جا سنجیده نمی‌شود: فهرستِ صفحه‌ها و تب‌ها فقط در
    فرانت است (`navModel` / `moduleSections` / `moduleLists`) و آوردنِ نسخه‌ی دومش
    به سرور یعنی دو فهرست که دیر یا زود واگرا می‌شوند. شناسه‌ی ناشناخته هنگامِ
    نمایش کنار گذاشته می‌شود، پس کارتِ مرده نمی‌ماند. سرور فقط شکل و اندازه را
    می‌سنجد تا ستون آشغال‌دانی نشود.
    """

    cards: list[str] = Field(default_factory=list, max_length=MAX_CARDS)


class DashboardCardsOut(BaseModel):
    #: `None` یعنی کاربر هنوز انتخاب نکرده و پیش‌فرض‌ها نشان داده می‌شوند.
    cards: list[str] | None = None
