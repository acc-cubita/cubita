"""«ثبت فاکتور» چه‌قدر کار انجام دهد — انتخابِ خودِ کسب‌وکار.

فصلِ «جداسازیِ فاکتور فروش از خروجِ انبار» سه حقیقت را از هم جدا کرد: سندِ
**تجاری** (فاکتور)، سندِ **حسابداری**، و **خروجِ فیزیکی**. این جداسازی درست است
و برگشت‌پذیر نیست — کسب‌وکاری که امروز فاکتور می‌دهد و هفته‌ی بعد کالا را
می‌فرستد، بدونش اصلاً نمی‌تواند درست کار کند.

ولی برای مغازه‌ای که فاکتور و تحویل یک لحظه‌اند، سه سند یعنی دو دکمه‌ی اضافه و
دو فراموشیِ ممکن: فاکتوری که سندِ حسابداری ندارد، و کالایی که از انبار کم نشده.

پس این‌جا **سیاست** است نه معماری: هر دو مسیر از همان `post_sales_invoice` و
همان سرویس‌های خروج و سند می‌گذرند؛ تنها چیزی که عوض می‌شود این است که آن دو گام
**خودکار** انجام شوند یا به دستِ کاربر بمانند.

مرزِ «سیاست و یکپارچگی» هم سرِ جایش می‌ماند: این پرچم تعیین می‌کند *چه زمانی*
سند و خروج ساخته شوند، نه اینکه بشود بی‌سند فروخت یا موجودیِ نداشته را برد.
"""
from __future__ import annotations

from sqlalchemy.orm import Session

from app.models.tenant import Tenant
from app.tenant_context import session_tenant

#: سیاست‌های صدورِ فاکتور فروش.
POSTING_MODES = ("immediate", "staged")

#: **پیش‌فرض `immediate` است، نه رفتارِ تازه.** جداسازی برای کسبِ‌وکارهایی ساخته
#: شد که لازمش دارند؛ بقیه نباید یک‌شبه دو گامِ دستیِ تازه بگیرند و ندانند چرا
#: فاکتورشان در دفتر نیست.
DEFAULT_POSTING_MODE = "immediate"

POSTING_MODE_LABELS = {
    "immediate": "خودکار",
    "staged": "دومرحله‌ای",
}

POSTING_MODE_HINTS = {
    "immediate": "با «ثبت فاکتور»، سندِ حسابداری و خروجِ انبار هم همان لحظه صادر می‌شوند.",
    "staged": "فاکتور فقط ثبت می‌شود؛ سندِ حسابداری و خروجِ انبار را بعداً خودتان صادر می‌کنید.",
}

POSTING_MODE_EFFECTS = {
    "immediate": [
        "یک کلیک: فاکتور، سندِ حسابداری و خروجِ انبار با هم.",
        "انتخابِ انبار الزامی می‌شود، چون کالا همان لحظه از آن کم می‌شود.",
        "مناسبِ فروشِ حضوری که فاکتور و تحویل یک لحظه‌اند.",
    ],
    "staged": [
        "فاکتور بدونِ سندِ حسابداری و بدونِ کسرِ موجودی ثبت می‌شود.",
        "از فهرستِ فاکتورها «صدور سند حسابداری» و «صدور خروج انبار» را جدا می‌زنید.",
        "می‌توانید بخشی از کالای یک فاکتور را حالا و بقیه را بعداً بفرستید.",
        "مناسبِ فروشی که تحویلش روزِ دیگری است.",
    ],
}


def get_posting_mode(db: Session) -> str:
    """سیاستِ این کسب‌وکار. بدونِ زمینه‌ی مستأجر، پیش‌فرض — تا seed و اسکریپت نشکنند."""
    tenant_id = session_tenant(db)
    if tenant_id is None:
        return DEFAULT_POSTING_MODE
    tenant = db.get(Tenant, tenant_id)
    if tenant is None:
        return DEFAULT_POSTING_MODE
    return tenant.sales_invoice_posting or DEFAULT_POSTING_MODE


def set_posting_mode(tenant: Tenant, mode: str) -> str:
    if mode not in POSTING_MODES:
        raise ValueError("سیاستِ صدورِ فاکتور فروش نامعتبر است")
    tenant.sales_invoice_posting = mode
    return mode


def posts_immediately(db: Session) -> bool:
    """آیا «ثبت فاکتور» باید سند و خروج را هم بزند؟"""
    return get_posting_mode(db) == "immediate"
