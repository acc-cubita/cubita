"""کمک‌کننده‌ی مهاجرت برای عبور از RLS.

مهاجرت‌ها بدون زمینه‌ی مستأجر اجرا می‌شوند — و نباید هم اجرا شوند، چون کارشان روی
داده‌ی *همه‌ی* مستأجرهاست. ولی سیاست ایزوله‌سازی `current_setting('app.tenant_id')`
را می‌خواند و وقتی خالی است صفر ردیف مچ می‌کند. نتیجه: هر UPDATE داده‌ای در مهاجرت
بی‌صدا صفر ردیف را عوض می‌کند و مهاجرت با موفقیت گزارش می‌دهد.

این دقیقاً یک‌بار اتفاق افتاد: مهاجرت system_role موفق اعلام شد و هیچ حسابی
علامت نخورد.

`SET row_security = off` جواب نمی‌دهد؛ آن گزینه به‌جای دور زدن، خطا می‌دهد. تا وقتی
FORCE روشن است حتی مالک جدول هم مشمول سیاست است. پس FORCE موقتاً و داخل همان
تراکنشِ مهاجرت برداشته می‌شود. چون DDL در Postgres تراکنشی است، اگر مهاجرت شکست
بخورد FORCE هم با آن برمی‌گردد و پنجره‌ای باز نمی‌ماند.

راه‌حل بلندمدت یک نقش جدا با BYPASSRLS برای مهاجرت‌هاست، که ساختنش superuser
می‌خواهد. تا آن وقت، این تنها راه امنِ در دسترس است.

## کاربردِ دوم — افزودنِ کلیدِ خارجی به جدولی که ردیف دارد

این مورد **گران** کشف شد: استقرارِ تولید وسطِ مهاجرتِ `0139` شکست خورد با

    invalid input syntax for type uuid: ""

خودِ `ADD FOREIGN KEY` مقصر نبود؛ **اعتبارسنجیِ** آن بود. Postgres پس از افزودنِ
قید یک اسکنِ راستی‌آزمایی می‌زند:

    SELECT fk.col FROM ONLY child fk LEFT JOIN ONLY parent pk ON pk.id = fk.col
    WHERE pk.id IS NULL AND fk.col IS NOT NULL

و آن اسکن مشمولِ سیاستِ RLSِ هر دو جدول است. سیاست
`current_setting('app.tenant_id', true)::uuid` را ارزیابی می‌کند، در مهاجرت آن
متغیر تهی است، و `''::uuid` خطا می‌دهد — نه «صفر ردیف»، بلکه شکستِ کلِ مهاجرت.

**چرا هیچ‌کس پیش از تولید ندیدش — دو دلیل، و هر دو مهم‌اند:**

۱. روی جدولِ **خالی** هرگز رخ نمی‌دهد: اسکنی نیست تا سیاست ارزیابی شود. هر
   راستی‌آزماییِ مهاجرت که روی اسکیمای تازه انجام شود، این طبقه از باگ را
   **ساختاراً** نمی‌بیند. داده باید *پیش از* مهاجرت کاشته شود، نه بعدش.
۲. **نسخه‌ی Postgres فرق می‌کند.** روی ۱۷ برنامه‌ریز آن اسکنِ داخلی را حذف
   می‌کند و مهاجرت سبز می‌شود؛ روی ۱۴ (همان که تولید دارد) اسکن می‌شود و
   می‌ترکد. یعنی ماشینِ توسعه‌ی PG 17 **نمی‌تواند** این را بگیرد، هر چه‌قدر هم
   داده داشته باشد.

پس هر `create_foreign_key` یا `add_column`ِ دارای `ForeignKey` روی جدولی که
ممکن است ردیف داشته باشد، داخلِ همین `rls_disabled` می‌رود — با **هر دو** جدولِ
طرفِ قید.
"""
from contextlib import contextmanager

import sqlalchemy as sa


@contextmanager
def rls_disabled(conn, tables):
    """FORCE را روی جدول‌های داده‌شده موقتاً برمی‌دارد تا مهاجرت همه‌ی ردیف‌ها را ببیند."""
    tables = list(tables)
    for t in tables:
        conn.execute(sa.text(f"ALTER TABLE {t} NO FORCE ROW LEVEL SECURITY"))
    try:
        yield
    finally:
        for t in tables:
            conn.execute(sa.text(f"ALTER TABLE {t} FORCE ROW LEVEL SECURITY"))
